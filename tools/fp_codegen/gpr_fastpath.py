#!/usr/bin/env python3
"""gpr_fastpath.py: exact straight-line fast path for the GPR save/restore helpers (__savegprlr_N / __restgprlr_N, N=14..31).

  header OUT.h                     write gpr_helpers_calls.h (recomp_calls::save<N> / restore<N>, always_inline)
  helpers IN326.cpp OUT.cpp [--twin FLAG]
                                   rewrite the chunk that defines the 36 helpers (ppc_recomp.326.cpp in the api26 corpus):
                                   each helper becomes the frameless fast path; its original body (after the prologue) stays
                                   as extern "C" recomp_calls_gpr_body_{save,rest}_N, the cold path. --twin FLAG keeps the
                                   original helper too and chooses at entry while extern "C" std::atomic<unsigned> FLAG != 0
                                   (in-run A/B; FLAG is defined in this chunk, default 0 = original).
  sites IN.cpp OUT.cpp [--twin FLAG] [--direct]
                                   inline placement (--direct: only skip the weak-wrapper hop, call __imp____*gprlr_N): every call statement `[else ]__savegprlr_N(ctx, base);` /
                                   `__restgprlr_N(ctx, base);` of a caller chunk calls recomp_calls::save<N> / restore<N>
                                   instead (with --twin: only while FLAG != 0, else the original call). Needs the helpers
                                   chunk rewritten by `helpers` (it defines the cold bodies).

Why exact (v407 corpus: RECOMP_GUEST_MEMORY_ATOMIC=1, constant-window tree predicate, v243 helpers). The original helper
runs PPC_FUNC_PROLOGUE() (the guestCheckpoint countdown in the context's tail padding, slow call with the label
"__imp____savegprlr_N"), then v243's block test, then one relaxed atomic 64-bit access per register in ascending address
order plus the 32-bit r12 word, or the generated per-access path. The fast path performs the same checkpoint (same
decrement, same condition; the slow case tail-calls recomp_calls_gpr_cp_*_N = the same slow call with the same label and
countdown pointer, then the original body), the same block test (v243's fastBlock: equal to every access's own fast
predicate, tests/cw_tree_test.cpp + v243), and when it holds the same accesses: with RECOMP_CALLS_GPR_PAIRS (default 1)
two adjacent 8-byte-aligned registers go through one STP/LDP, which AArch64 performs as two single-copy-atomic 64-bit
accesses (the relaxed-atomic contract: no tearing, no ordering between different locations), else one access each as
v243 does. Byte-reversed values, addresses, widths and the r12/lr results are those of the original. Without the block
test (misaligned r1, a window, a wrap) the original body runs unchanged, including v243's own diag-v243-baseline switch;
the fast path itself does not read recomp_v243_baseline (both of v243's paths are equal there).
The host differential test is tools/fp_codegen/gpr_fastpath_check.py. This tool contains no game code; generated
chunks stay under local-analysis/."""
from __future__ import annotations
import argparse, re, sys
from pathlib import Path

HELPER_DEF = re.compile(r'^PPC_FUNC_IMPL\(__imp____(save|rest)gprlr_(\d+)\)\s*\{\s*$')
SITE = re.compile(r'^(\s*)(else\s+)?__(save|rest)gprlr_(\d+)\(ctx, ?base\);(.*)$')
NS = range(14, 32)


def label(kind: str, n: int) -> str:
    return f'__imp____{"save" if kind == "save" else "rest"}gprlr_{n}'


def plan(n: int, phase: int) -> list[tuple[int, ...]]:
    """Register groups of N's block for r1 = 8*phase (mod 16): a pair (k, k+1) only where rk's slot is 16-byte aligned, so
    no STP/LDP crosses a 16-byte (hence a cache-line) boundary; rk lives at r1 - 8*(32-k) - 8 = 8*(phase+k+1) (mod 16).
    (A first version paired from rN regardless: on the host its line-crossing pairs were 1.5-3x SLOWER than v243.)"""
    out, k = [], n
    while k <= 31:
        if (k - phase - 1) % 2 == 0 and k + 1 <= 31:
            out.append((k, k + 1)); k += 2
        else:
            out.append((k,)); k += 1
    return out


def asm_block(kind: str, n: int, phase: int) -> tuple[str, list[str], list[tuple[int, ...]]]:
    """The asm text for N's register block at phase (base register %[p] = the slot of rN), operand names, groups."""
    count = 32 - n
    lines, names = [], []
    op = 'stp' if kind == 'save' else 'ldp'
    one = 'str' if kind == 'save' else 'ldr'
    groups = plan(n, phase)
    for g in groups:
        if len(g) == 2:
            lines.append(f'{op} %x[a{g[0]}], %x[a{g[1]}], [%[p], #{8 * (g[0] - n)}]')
        else:
            lines.append(f'{one} %x[a{g[0]}], [%[p], #{8 * (g[0] - n)}]')
        names += [f'a{k}' for k in g]
    lines.append(f'{one} %w[w], [%[p], #{8 * count}]')
    return '\\n\\t'.join(lines), names, groups


def header() -> str:
    out = []
    w = out.append
    w('#pragma once\n// gpr_helpers_calls.h (package E "calls", generated by tools/fp_codegen/gpr_fastpath.py header; do not edit).\n'
      '// Exact straight-line fast path of the GPR save/restore helpers: see the tool\'s docstring for the argument.\n'
      '#include <atomic>\n#include <cstddef>\n#include <cstdint>\n#include "guest_parallel_wake.h"\n'
      '#if !defined(RECOMP_GUEST_MEMORY_MODEL) || RECOMP_GUEST_MEMORY_MODEL != 1\n'
      '#error "recomp_calls: paired accesses equal the relaxed per-register accesses only in guest memory model 1"\n#endif\n'
      '#if !(defined(RECOMP_GUEST_SPECIAL_CONST_WINDOWS) && RECOMP_GUEST_SPECIAL_CONST_WINDOWS && '
      'defined(RECOMP_GUEST_SPECIAL_CONST_WINDOWS_TREE) && RECOMP_GUEST_SPECIAL_CONST_WINDOWS_TREE)\n'
      '#error "recomp_calls: the block test equals the per-access test only with the constant-window tree predicate"\n#endif\n'
      '#ifndef PPC_RUNTIME_CHECKPOINT\n#error "recomp_calls: the corpus prologue checkpoint (trace_prelude.h) is required"\n#endif\n'
      '#ifndef RECOMP_CALLS_GPR_PAIRS\n#define RECOMP_CALLS_GPR_PAIRS 1\n#endif\n'
      '#if RECOMP_CALLS_GPR_PAIRS && !defined(__aarch64__)\n#undef RECOMP_CALLS_GPR_PAIRS\n#define RECOMP_CALLS_GPR_PAIRS 0\n#endif\n')
    w('// The original helpers\' bodies after PPC_FUNC_PROLOGUE() (cold path), and checkpoint-slow-then-body (defined in the\n'
      '// helpers chunk by gpr_fastpath.py helpers).\nextern "C" {\n')
    for kind in ('save', 'rest'):
        for n in NS:
            w(f'void recomp_calls_gpr_body_{kind}_{n}(PPCContext& __restrict ctx, uint8_t* base);\n')
            w(f'void recomp_calls_gpr_cp_{kind}_{n}(PPCContext& __restrict ctx, uint8_t* base);\n')
    w('}\n')
    w('// The original prologue with an explicit checkpoint label (a moved copy keeps the helper\'s own __func__).\n'
      '#define RECOMP_CALLS_PROLOGUE(label) do { __builtin_assume(((size_t)base & 0x1F) == 0); '
      '::recomp::bootstrap::guestCheckpoint(ctx, label, sizeof(label) - 1); } while (false)\n')
    w('namespace recomp_calls {\n'
      '// v243\'s fastBlock (recomp_v243::fastBlock), verbatim: [address, address + bytes) meets none of the three windows.\n'
      '[[gnu::always_inline]] inline bool fastBlock(std::uint32_t address, std::uint32_t bytes) {\n'
      '    const std::uint64_t last = std::uint64_t{address} + bytes - 1;\n'
      '    using namespace recomp::bootstrap;\n'
      '#if defined(RECOMP_CALLS_MUTANT_WINDOW) // test mutant: window B ends 8 bytes early\n'
      '    if (last < 0x7FC80000u) return last < guestSpecialWindowB || address >= guestSpecialWindowB + guestSpecialWindowBytes - 8;\n'
      '#else\n'
      '    if (last < 0x7FC80000u) return last < guestSpecialWindowB || address >= guestSpecialWindowB + guestSpecialWindowBytes;\n'
      '#endif\n'
      '    if (address < 0x7FEB0000u) return false;\n'
      '    return last < guestSpecialWindowA || (address >= guestSpecialWindowA + guestSpecialWindowBytes && last <= 0xFFFFFFFFu);\n'
      '}\n'
      '// guestCheckpoint\'s fast half (guest_parallel_wake.h): the decrement and the slow-path condition. true = no slow call.\n'
      '[[gnu::always_inline]] inline bool checkpointFast(PPCContext& ctx) {\n'
      '#if defined(RECOMP_CALLS_MUTANT_NO_CHECKPOINT) // test mutant: no countdown decrement\n'
      '    return true;\n'
      '#else\n'
      '    auto* countdown = ::recomp::bootstrap::guestCheckpointCountdown(ctx);\n'
      '    const auto next = static_cast<std::uint32_t>(*countdown) - 1U;\n'
      '    *countdown = static_cast<std::int32_t>(next);\n'
      '    return !__builtin_expect((next >= ::recomp::bootstrap::GuestCheckpointCountdownLimit) |\n'
      '        (__atomic_load_n(&recomp_guest_checkpoint_attention, __ATOMIC_RELAXED) != 0U), 0);\n'
      '#endif\n'
      '}\n'
      'template<int N> void save(PPCContext& __restrict ctx, std::uint8_t* base) = delete;\n'
      'template<int N> void restore(PPCContext& __restrict ctx, std::uint8_t* base) = delete;\n')
    for n in NS:
        count = 32 - n
        bytes_ = 8 * count + 4
        regs = [f'r{k}' for k in range(n, 32)]
        # save
        w(f'template<> [[gnu::always_inline]] inline void save<{n}>(PPCContext& __restrict ctx, std::uint8_t* base) {{\n')
        w('    __builtin_assume(((size_t)base & 0x1F) == 0);\n')
        w(f'    if (!checkpointFast(ctx)) {{ recomp_calls_gpr_cp_save_{n}(ctx, base); return; }}\n')
        w(f'    const std::uint32_t sp = ctx.r1.u32, lo = sp - {8 * count + 8}u;\n')
        w(f'    if ((sp & 7u) || !fastBlock(lo, {bytes_}u)) {{ recomp_calls_gpr_body_save_{n}(ctx, base); return; }}\n')
        w('    std::uint8_t* const p = base + lo;\n')
        w('#if RECOMP_CALLS_GPR_PAIRS\n')
        w('    ' + ' '.join(f'const std::uint64_t a{k} = __builtin_bswap64(ctx.r{k}.u64);' for k in range(n, 32)) + '\n')
        w('    const std::uint32_t w = __builtin_bswap32(ctx.r12.u32);\n')
        for phase in (0, 1):
            text, names, groups = asm_block('save', n, phase)
            ops = [f'[{nm}] "r"({nm})' for nm in names]
            pair = next((g for g in groups if len(g) == 2), None)
            w(f'    {"if (!(sp & 8u))" if phase == 0 else "else"} {{ // r1 = {8 * phase} mod 16\n')
            if pair:
                a0, a1 = f'a{pair[0]}', f'a{pair[1]}'
                swapped = [o.replace(f'({a0})', '(@)').replace(f'({a1})', f'({a0})').replace('(@)', f'({a1})') for o in ops]
                w('#if defined(RECOMP_CALLS_MUTANT_SWAP_PAIR) // test mutant: the first pair\'s registers swapped\n')
                w(f'        __asm__("{text}" : "=m"(*reinterpret_cast<std::uint8_t(*)[{bytes_}]>(p)) : [p] "r"(p), {", ".join(swapped)}, [w] "r"(w));\n')
                w('#else\n')
            w(f'        __asm__("{text}" : "=m"(*reinterpret_cast<std::uint8_t(*)[{bytes_}]>(p)) : [p] "r"(p), {", ".join(ops)}, [w] "r"(w));\n')
            if pair:
                w('#endif\n')
            w('    }\n')
        w('#else\n')
        for k, r in enumerate(regs):
            w(f'    ::recomp::bootstrap::storeGuestScalarRaw<std::uint64_t>(p + {8 * k}u, ctx.{r}.u64);\n')
        w(f'    ::recomp::bootstrap::storeGuestScalarRaw<std::uint32_t>(p + {8 * count}u, ctx.r12.u32);\n')
        w('#endif\n')
        w('#if defined(RECOMP_CALLS_MUTANT_OFFSET) // test mutant: r31 written one slot low (over r30)\n')
        w(f'    ::recomp::bootstrap::storeGuestScalarRaw<std::uint64_t>(p + {8 * (count - 1) - 8}u, ctx.r31.u64);\n' if count > 1 else
          f'    ::recomp::bootstrap::storeGuestScalarRaw<std::uint64_t>(p + 4u, ctx.r31.u64);\n')
        w('#endif\n')
        w('}\n')
        # restore
        w(f'template<> [[gnu::always_inline]] inline void restore<{n}>(PPCContext& __restrict ctx, std::uint8_t* base) {{\n')
        w('    __builtin_assume(((size_t)base & 0x1F) == 0);\n')
        w(f'    if (!checkpointFast(ctx)) {{ recomp_calls_gpr_cp_rest_{n}(ctx, base); return; }}\n')
        w(f'    const std::uint32_t sp = ctx.r1.u32, lo = sp - {8 * count + 8}u;\n')
        w(f'    if ((sp & 7u) || !fastBlock(lo, {bytes_}u)) {{ recomp_calls_gpr_body_rest_{n}(ctx, base); return; }}\n')
        w('    const std::uint8_t* const p = base + lo;\n')
        w('#if RECOMP_CALLS_GPR_PAIRS\n')
        w('    std::uint64_t ' + ', '.join(f'a{k}' for k in range(n, 32)) + '; std::uint32_t w;\n')
        for phase in (0, 1):
            text, names, groups = asm_block('rest', n, phase)
            outs = ', '.join(f'[{nm}] "=&r"({nm})' for nm in names)
            w(f'    {"if (!(sp & 8u))" if phase == 0 else "else"} // r1 = {8 * phase} mod 16\n')
            w(f'        __asm__("{text}" : {outs}, [w] "=&r"(w) : [p] "r"(p), "m"(*reinterpret_cast<const std::uint8_t(*)[{bytes_}]>(p)));\n')
        for k in range(n, 32):
            w(f'    ctx.r{k}.u64 = __builtin_bswap64(a{k});\n')
        w('    ctx.r12.u64 = __builtin_bswap32(w);\n')
        w('#else\n')
        for k, r in enumerate(regs):
            w(f'    ctx.{r}.u64 = ::recomp::bootstrap::loadGuestScalarRaw<std::uint64_t>(p + {8 * k}u);\n')
        w(f'    ctx.r12.u64 = ::recomp::bootstrap::loadGuestScalarRaw<std::uint32_t>(p + {8 * count}u);\n')
        w('#endif\n')
        w('#if !defined(RECOMP_CALLS_MUTANT_NO_LR) // test mutant: lr not set\n    ctx.lr = ctx.r12.u64;\n#endif\n')
        w('}\n')
    w('} // namespace recomp_calls\n')
    return ''.join(out)


def scan_helpers(lines: list[str]):
    """(start, end index of the closing brace, kind, n) of every GPR helper definition."""
    i = 0
    while i < len(lines):
        m = HELPER_DEF.match(lines[i])
        if not m:
            i += 1; continue
        j = i + 1
        while j < len(lines) and not lines[j].startswith('}'): j += 1
        yield i, j, m.group(1), int(m.group(2))
        i = j + 1


def checked_body(lines: list[str], i: int, j: int, kind: str, n: int) -> list[str]:
    body = lines[i + 1:j]
    if not body or body[0].strip() != 'PPC_FUNC_PROLOGUE();':
        raise SystemExit(f'{label(kind, n)}: body does not start with PPC_FUNC_PROLOGUE()')
    if any('PPC_FUNC_PROLOGUE' in l for l in body[1:]) or any(re.search(r'\breturn\b(?!;)', l.split('//', 1)[0]) for l in body):
        raise SystemExit(f'{label(kind, n)}: unexpected body shape')
    return body


def cold_defs(body: list[str], kind: str, n: int) -> list[str]:
    """recomp_calls_gpr_body_* (the original body after its prologue) and recomp_calls_gpr_cp_* (the prologue's slow
    checkpoint call with the helper's own label and countdown pointer, then that body)."""
    lab = label(kind, n)
    out = [f'extern "C" void recomp_calls_gpr_body_{kind}_{n}(PPCContext& __restrict ctx, uint8_t* base) {{ // {lab} after its prologue (gpr_fastpath.py)\n',
           '\t__builtin_assume(((size_t)base & 0x1F) == 0);\n']
    out.extend(body[1:]); out.append('}\n\n')
    out.append(f'extern "C" __attribute__((cold, noinline)) void recomp_calls_gpr_cp_{kind}_{n}(PPCContext& __restrict ctx, uint8_t* base) {{\n')
    out.append(f'\trecomp_guest_execution_checkpoint_slow(reinterpret_cast<std::int32_t*>(::recomp::bootstrap::guestCheckpointCountdown(ctx)), "{lab}", sizeof("{lab}") - 1);\n')
    out.append(f'\trecomp_calls_gpr_body_{kind}_{n}(ctx, base);\n}}\n\n')
    return out


def rewrite_helpers(src: str, twin: str = '') -> tuple[str, int]:
    lines = src.splitlines(keepends=True)
    out, prev, done = [], 0, set()
    for i, j, kind, n in scan_helpers(lines):
        body = checked_body(lines, i, j, kind, n)
        out.extend(lines[prev:i]); prev = j + 1
        lab = label(kind, n)
        out.extend(cold_defs(body, kind, n))
        fn = 'save' if kind == 'save' else 'restore'
        if twin:
            out.append(f'static __attribute__((noinline)) void recomp_calls_gpr_orig_{kind}_{n}(PPCContext& __restrict ctx, uint8_t* base) {{\n')
            out.append(f'\tRECOMP_CALLS_PROLOGUE("{lab}");\n')
            out.extend(body[1:]); out.append('}\n\n')
            # fair A/B (as macro_twin.py --dispatch): both sides behind the same flag load and a tail call
            out.append(f'static __attribute__((noinline)) void recomp_calls_gpr_fast_{kind}_{n}(PPCContext& __restrict ctx, uint8_t* base) {{\n')
            out.append(f'\trecomp_calls::{fn}<{n}>(ctx, base);\n}}\n\n')
            out.append(lines[i])
            out.append(f'\tif ({twin}.load(std::memory_order_relaxed)) recomp_calls_gpr_fast_{kind}_{n}(ctx, base); // gpr_fastpath twin\n')
            out.append(f'\telse recomp_calls_gpr_orig_{kind}_{n}(ctx, base);\n')
            out.append(lines[j])
        else:
            out.append(lines[i])
            out.append(f'\trecomp_calls::{fn}<{n}>(ctx, base); // gpr_fastpath (original body: recomp_calls_gpr_body_{kind}_{n})\n')
            out.append(lines[j])
        done.add((kind, n))
    out.extend(lines[prev:])
    if not done:
        return src, 0
    if len(done) != 36:
        raise SystemExit(f'expected the 36 GPR helpers, found {len(done)}')
    k = next(n for n, l in enumerate(out) if l.startswith('#include')) + 1
    decl = '#include <atomic>\n#include "gpr_helpers_calls.h" // gpr_fastpath.py\n'
    if twin:
        decl += f'extern "C" __attribute__((visibility("hidden"))) std::atomic<unsigned> {twin}; // gpr_fastpath twin switch\n'
        decl += f'std::atomic<unsigned> {twin}{{0}};\n'
    out.insert(k, decl)
    return ''.join(out), len(done)


def rewrite_sites(src: str, twin: str = '', mode: str = 'inline') -> tuple[str, int]:
    """mode 'inline': recomp_calls::save<N>/restore<N> at the call site; 'direct': call __imp____savegprlr_N directly (the
    weak wrapper only forwards and no hook replaces a helper, as direct_calls.py does for unhooked guest callees)."""
    lines = src.splitlines(keepends=True)
    n_done, used = 0, set()
    for i, l in enumerate(lines):
        code, sep, comment = l.partition('//')
        m = SITE.match(code.rstrip('\n'))
        if not m or m.group(5).strip():
            continue
        ind, els, kind, n = m.group(1), m.group(2) or '', m.group(3), int(m.group(4))
        fn = 'save' if kind == 'save' else 'restore'
        call = f'recomp_calls::{fn}<{n}>(ctx, base);' if mode == 'inline' else f'__imp____{kind}gprlr_{n}(ctx, base);'
        used.add((kind, n))
        if twin:
            call = f'{{ if ({twin}.load(std::memory_order_relaxed)) {call} else __{kind}gprlr_{n}(ctx, base); }}'
        lines[i] = f'{ind}{els}{call}' + (f' //{comment}' if sep else '\n')
        n_done += 1
    if n_done:
        k = next((n for n, l in enumerate(lines) if l.startswith('#include')), None)
        if k is not None:  # a whole chunk (a body fragment from the checker has no includes)
            decl = '#include <atomic>\n'
            if mode == 'inline':
                decl += '#include "gpr_helpers_calls.h" // gpr_fastpath.py sites\n'
            else:
                decl += ''.join(f'PPC_FUNC_IMPL(__imp____{kind}gprlr_{n}); // gpr_fastpath.py sites --direct\n' for kind, n in sorted(used))
            if twin:
                decl += f'extern "C" __attribute__((visibility("hidden"))) std::atomic<unsigned> {twin}; // gpr_fastpath twin switch\n'
            last = max(n for n, l in enumerate(lines[:80]) if l.startswith('#include'))
            lines.insert(last + 1, decl)
    return ''.join(lines), n_done


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('cmd', choices=['header', 'helpers', 'sites'])
    ap.add_argument('paths', nargs='+')
    ap.add_argument('--twin', default='')
    ap.add_argument('--direct', action='store_true', help='sites: call __imp____*gprlr_N directly instead of inlining')
    a = ap.parse_args()
    if a.cmd == 'header':
        Path(a.paths[0]).write_text(header(), encoding='utf-8', newline='\n'); print(f'wrote {a.paths[0]}'); return 0
    src = Path(a.paths[0]).read_text(encoding='utf-8')
    out, n = rewrite_helpers(src, a.twin) if a.cmd == 'helpers' else rewrite_sites(src, a.twin, 'direct' if a.direct else 'inline')
    Path(a.paths[1]).write_text(out, encoding='utf-8', newline='\n')
    print(f'{a.paths[0]}: {n} {"helpers" if a.cmd == "helpers" else "call sites"} rewritten')
    return 0


if __name__ == '__main__':
    sys.exit(main())
