#!/usr/bin/env python3
"""Prepare an executable private test of an actual generated switch fragment."""
from pathlib import Path
import argparse
import os
import re
import subprocess

from switch_tables import SwitchTable, parse_switch_metadata


def checked_fragment(source: str, table: SwitchTable) -> str:
    """Match the exact audited live-target lowering; never execute arbitrary text."""
    lines = [f'\tswitch (ctx.r{table.selector}.u32) {{']
    for i, label in enumerate(table.labels):
        lines.extend([f'\tcase {i}:', f'\t\tif (ctx.ctr.u32 != 0x{label:X}U) {{',
            '\t\t\tPPC_CALL_INDIRECT_FUNC(ctx.ctr.u32); return;', '\t\t}', f'\t\tgoto loc_{label:X};'])
    lines.extend(['\tdefault:', '\t\tPPC_CALL_INDIRECT_FUNC(ctx.ctr.u32); return;', '\t}'])
    expected = '\n'.join(lines)
    if source.count(expected) != 1:
        raise ValueError('generated switch is missing, ambiguous or differs from live-target lowering')
    for label in table.labels:
        if len(re.findall(rf'^loc_{label:X}:$', source, re.M)) != 1:
            raise ValueError('case target lacks one actual local label')
    # Return the actual generated bytes, not the expected rendering.
    start = source.index(expected)
    return source[start:start+len(expected)]


def fixture_source(fragment: str, table: SwitchTable) -> str:
    text = '#include "ppc_context.h"\n#include <array>\n#include <cassert>\n#include <cstdint>\n'
    text += 'static bool fallback, selected; static uint32_t observed;\n'
    text += '#undef PPC_CALL_INDIRECT_FUNC\n#define PPC_CALL_INDIRECT_FUNC(target) do { fallback=true; observed=(target); } while(false)\n'
    text += 'static void probe(PPCContext& ctx) {\n'+fragment+'\n'
    for label in sorted(set(table.labels)):
        text += f'loc_{label:X}: selected=true; observed=0x{label:X}U; return;\n'
    text += '}\nint main() {\n'
    text += f'const std::array<uint32_t,{len(table.labels)}> targets{{'+','.join(f'0x{x:X}U' for x in table.labels)+'};\n'
    text += 'for (uint64_t high : {0ULL,0x1234567800000000ULL,0xFFFFFFFF00000000ULL}) {\n'
    text += 'for (uint32_t i=0; i<targets.size()+2; ++i) {\n'
    text += 'for (bool matching : {false,true}) {\nPPCContext ctx{}; fallback=selected=false; observed=0;\n'
    text += f'ctx.r{table.selector}.u64=high|i;\n'
    text += 'const uint32_t target=i<targets.size()?targets[i]:0;\n'
    text += 'ctx.ctr.u64=high|(matching?target:(target^4U)); const auto originalCtr=ctx.ctr.u64;\n'
    text += 'ctx.r1.u64=0x70001230; ctx.lr=0xABCDEF0012345678ULL; ctx.r24.u64=0xFAFAFBFBFCFCFDFDULL; probe(ctx);\n'
    text += 'const bool expected=i<targets.size()&&matching; assert(selected==expected && fallback!=expected);\n'
    text += 'assert(observed==uint32_t(originalCtr)); assert(ctx.ctr.u64==originalCtr);\n'
    text += 'assert(ctx.r1.u64==0x70001230 && ctx.lr==0xABCDEF0012345678ULL && ctx.r24.u64==0xFAFAFBFBFCFCFDFDULL);\n'
    text += f'assert(ctx.r{table.selector}.u64==(high|i));\n'
    text += '}}}\n}\n'
    return text


def main() -> int:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('metadata',type=Path)
    parser.add_argument('source',type=Path)
    parser.add_argument('--dispatch',type=lambda x:int(x,0),required=True)
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    root=Path(__file__).resolve().parents[2]
    for path in (args.metadata,args.source,args.output):
        lexical=path.expanduser().absolute()
        if lexical.is_symlink() or lexical!=lexical.resolve() or not lexical.is_relative_to(root/'local-analysis') \
                or subprocess.run(['git','check-ignore','--quiet','--',str(lexical)],cwd=root).returncode:
            raise ValueError('fixture paths must be private ignored regular paths without symlinks')
    if not 0<args.metadata.stat().st_size<=1024*1024 or not 0<args.source.stat().st_size<=8*1024*1024:
        raise ValueError('fixture input size exceeds its bound')
    tables=[t for t in parse_switch_metadata(args.metadata.read_text()) if t.base==args.dispatch]
    if len(tables)!=1 or tables[0].selector in (1,24):
        raise ValueError('one switch with non-canary selector required')
    table=tables[0]
    text=fixture_source(checked_fragment(args.source.read_text(),table),table)
    args.output.parent.mkdir(parents=True,exist_ok=True)
    descriptor=os.open(args.output,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW,0o600)
    with os.fdopen(descriptor,'w', encoding='utf-8', newline='\n') as stream: stream.write(text)
    print(f'Prepared actual generated switch fragment: {(len(table.labels)+2)*6} native dispatch checks; no case bodies executed')
    return 0


if __name__=='__main__':
    try: raise SystemExit(main())
    except (ValueError,OSError): raise SystemExit('private switch fixture validation failed')
