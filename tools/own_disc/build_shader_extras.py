def fetches(code):
    if not code or len(code) % 12:
        raise ValueError('fetch instruction alignment refused')
    words = struct.unpack(f'>{len(code)//4}I', code)
    end, slot, result = len(words)//3, 0, []
    while slot < end:
        a,b,c = words[3*slot:3*slot+3]
        for lo,hi in ((a,b&65535),((b>>16)|((c<<16)&0xffffffff),c>>16)):
            if (hi>>12)&15 in rules.EXEC_OPCODES:
                address,count,sequence = lo&4095,(lo>>12)&7,(lo>>16)&4095
                if address: end=min(end,address)
                if address+count > len(words)//3:
                    raise ValueError('fetch clause extent refused')
                for i in range(count):
                    if sequence>>(2*i)&1:result.append(words[3*(address+i):3*(address+i)+3])
        slot+=1
    return result


def classify(code):
    fs=fetches(code)
    n_gradient=sum(w[0]&31==18 for w in fs)
    n_set=sum(w[0]&31==24 for w in fs)
    n_lod=sum(w[0]&31==1 and bool(w[1]>>29&1) for w in fs)
    texture=[w for w in fs if w[0]&31==1]
    denorm=any(w[0]>>25&1 for w in texture)
    if sum((denorm,n_gradient>0,n_set>0 or n_lod>0))>1:
        raise ValueError('overlapping override classes require explicit implementation')
    if denorm:
        if len(texture)!=1:raise ValueError('denorm rewrite requires exactly one texture fetch')
        return 'denorm',1,0
    if n_gradient:return 'gradient',n_gradient,0
    if n_set or n_lod:
        if not n_set or not n_lod:raise ValueError('unpaired register LOD refused')
        return 'reglod',n_set,n_lod
    return None,0,0


def denorm_source(old):
    main=old.index('shaderMain(')
    if old[main:].count('tfetch2D(')!=1 or old.count(rules.ANCHOR)!=1:
        raise ValueError('denorm HLSL shape refused')
    text=old[:main]+old[main:].replace('tfetch2D(','tfetch2DUnnormalized(',1)
    return text.replace(rules.ANCHOR,rules.HELPER.strip()+'\n\n'+rules.ANCHOR,1)


def gradient_change(old,new,count):
    changes=[x for x in difflib.ndiff(old.splitlines(),new.splitlines()) if x[:2] in ('+ ','- ')]
    if len(changes)!=count or any(not x.startswith('+ ') or 'ddx(' not in x or 'ddy(' not in x for x in changes):
        raise ValueError('gradient HLSL delta refused')


def checked_record(root,receipt,container):
    folder=root/receipt['record']
    if folder.is_symlink() or not folder.resolve().is_relative_to(root.resolve()):
        raise ValueError('record path refused')
    source=(folder/'container.xenos').read_bytes()
    if sha(source)!=container['sha256'] or receipt['container_sha256']!=container['sha256']:
        raise ValueError('disc-to-record producer identity refused')
    return folder


def include_text(kind,rows):
    names={'denorm':('Denorm','local-analysis/attempts/v56/tools/make_denorm_overrides.py'),
           'gradient':('Gradient','local-analysis/attempts/v76/tools/make_gradient_overrides.py'),
           'reglod':('RegLod','local-analysis/agents/ship-week/dusk-speckle/tools/make_reglod_overrides.py')}
    name,provenance=names[kind]
    # Preserve historical formatting for exact comparison; report records the new producer.
    text=[f'// Generated by {provenance} (game-derived; do not edit).']
    if kind=='reglod':text.append('// The pack pixel shaders with a register-LOD texture fetch (Xenos setTexLOD + tfetch UseRegisterLOD), re-translated with it.')
    for i,(key,blob) in enumerate(sorted(rows)):
        if len(blob)%4 or blob[:4]!=b'\x03\x02\x23\x07':raise ValueError('override module framing refused')
        words=struct.unpack(f'<{len(blob)//4}I',blob)
        text.append(f'static const std::uint32_t {name}Override{i}[]={{'+','.join(f'0x{w:08x}' for w in words)+'};')
    text.append(f'static const DenormOverride {name}Overrides[]={{')
    text += [f'    {{0x{key:016x}ull,{len(blob)//4}u,{name}Override{i}}},' for i,(key,blob) in enumerate(sorted(rows))]
    text.append('};')
    return '\n'.join(text)+'\n'


def run_tool(argv,folder,tag,env):
    p=subprocess.run(list(map(str,argv)),cwd=folder,env=env,stdout=subprocess.PIPE,stderr=subprocess.STDOUT)
    (folder/(tag+'.log')).write_bytes(p.stdout)
    if p.returncode:raise ValueError(tag+' tool refused; private log preserved')


def compile_hlsl(config,folder,source,output,tag):
    env=shader_toolchain.library_environment(config['compiler_library_directory'])
    run_tool([config['dxc'],'-T','ps_6_0','-E','shaderMain','-HV','2021','-all-resources-bound','-spirv',
      '-fspv-target-env=vulkan1.1','-fvk-use-dx-layout','-Qstrip_debug','-Fo',output,source,
      '-D','XENOS_RECOMP_DESCRIPTOR_CONSTANTS=1'],folder,tag+'-dxc',env)
    run_tool([config['spirv_validator'],'--target-env','vulkan1.1','--relax-block-layout',output],folder,tag+'-validate',env)
    return output.read_bytes()


def overlays(args):
    import generic_shader_pack as g
    started=time.monotonic()
    inventory,items=validate_inventory(args.inventory)
    records=json.loads((args.translations/'translation.json').read_text())
    if records['failed'] or records['diagnostic_limit'] is not None:
        raise ValueError('overlay requires the full validated translation run')
    pack=args.translations/'generic-shaders.bin'
    if sha(pack.read_bytes())!=records['pack_sha256']:raise ValueError('baseline pack identity refused')
    entries=read_pack(pack.read_bytes())
    by_sha={r['container_sha256']:r for r in records['records'] if r['status']=='validated'}
    config=shader_toolchain.load(args.toolchain,args.host_tools,args.ndk,extras=True)
    if set(config)!=set(shader_toolchain.BASE+shader_toolchain.EXTRAS):raise ValueError('toolchain fields refused')
    paths={k:Path(v).resolve(strict=True) for k,v in config.items()}
    config={k:str(v) for k,v in paths.items()}
    inputs={str(p):sha(p.read_bytes()) for p in paths.values() if p.is_file()}
    for p in paths['compiler_library_directory'].iterdir():
        if p.is_file():inputs[str(p)]=sha(p.read_bytes())
    for p in [Path(__file__),Path(rules.__file__),Path(shader_toolchain.__file__),args.inventory/'inventory.json',args.translations/'translation.json',
              *([args.toolchain] if args.toolchain else []),
              args.repo/'tools/iter/generic_shader_pack.py',Path(__file__).with_name('build_shader_pack.py')]:
        inputs[str(p.resolve())]=sha(p.read_bytes())
    selected={}
    # Exact current runtime family; the superset remains in the standalone pack.
    for item in items:
        if any('/fxl_final_final/' in o['origin'] for o in item['origins']):selected.setdefault(item['key'],item)
    tasks=[];swizzles=[]
    for key,item in sorted(selected.items()):
        folder=checked_record(args.translations,by_sha[item['sha256']],item)
        code,elements,*_=g.parse_container((folder/'container.xenos').read_bytes(),item['stage'])
        if sha((folder/'translated.spv').read_bytes())!=entries[key]['spirv_sha256']:
            raise ValueError('selected baseline differs from generated pack')
        for filename in ('container.xenos','translated.hlsl','translated.spv'):
            p=folder/filename;inputs[str(p.resolve())]=sha(p.read_bytes())
        if item['stage']=='vertex':
            if elements:
                sw=[struct.unpack_from('>I',code,12*a+4)[0]&4095 for a,*_ in elements]
                swizzles.append((int(key,16),sw))
        else:
            kind,n_set,n_lod=classify(code)
            if kind:tasks.append((kind,int(key,16),folder,n_set,n_lod))
    if not 1<=args.jobs<=4:raise ValueError('jobs must be 1..4')
    if args.check:
        print('EXTRAS_CHECK PASS',dict(collections.Counter(t[0] for t in tasks)),'swizzles',len(swizzles));return 0
    require_bulk_priority(len(tasks))
    args.output.mkdir(parents=True,exist_ok=False)
    write_json(args.output/'run-inputs.json',dict(inputs=inputs,jobs=args.jobs))
    def translate(task):
        kind,key,record,n_set,n_lod=task
        folder=args.output/'records'/kind/f'{key:016x}';folder.mkdir(parents=True)
        old=(record/'translated.hlsl').read_text();baseline=(record/'translated.spv').read_bytes()
        control=compile_hlsl(config,folder,record/'translated.hlsl',folder/'control.spv','control')
        if control!=baseline:raise ValueError('control compiler failed baseline reproduction')
        source=folder/'translated.hlsl'
        if kind=='denorm':source.write_text(denorm_source(old), encoding='utf-8', newline='\n')
        else:
            env=shader_toolchain.library_environment(config['compiler_library_directory'])
            run_tool([config[kind+'_translator'],record/'container.xenos',source,config[kind+'_header']],folder,'translate',env)
            new=source.read_text()
            if kind=='gradient':gradient_change(old,new,n_set)
            elif rules.hlsl_change(old,new,n_set,n_lod):raise ValueError('register LOD HLSL delta refused')
        blob=compile_hlsl(config,folder,source,folder/'translated.spv','override')
        if baseline==blob:raise ValueError('override unchanged')
        if kind=='reglod':
            before,after=rules.opcode_counts(baseline),rules.opcode_counts(blob)
            if after[88]!=before[88]+n_lod or after[87]!=before[87]-n_lod:raise ValueError('REGISTER-LOD sampling connection refused')
        return kind,key,blob
    rows=collections.defaultdict(list)
    with ThreadPoolExecutor(max_workers=args.jobs) as executor:
        for kind,key,blob in executor.map(translate,tasks):rows[kind].append((key,blob))
    outputs={}
    for kind in ('denorm','gradient','reglod'):
        p=args.output/f'generic_{kind}_overrides.inc';p.write_text(include_text(kind,rows[kind]), encoding='utf-8', newline='\n')
        outputs[p.name]=dict(sha256=sha(p.read_bytes()),bytes=p.stat().st_size,modules=len(rows[kind]))
    text=['// Generated by tools/own_disc/build_shader_extras.py from fresh disc records.',
          '// {canonical microcode key, element count, container vfetch destination swizzle per pack element}']
    text += ['{0x%016xull,%d,{%s}},'%(key,len(sw),','.join('0x%03x'%s for s in sw)) for key,sw in sorted(swizzles)]
    p=args.output/'generic_container_swizzles.inc';p.write_text('\n'.join(text)+'\n', encoding='utf-8', newline='\n')
    outputs[p.name]=dict(sha256=sha(p.read_bytes()),bytes=p.stat().st_size,rows=len(swizzles))
    if any(sha(Path(p).read_bytes())!=digest for p,digest in inputs.items()):raise ValueError('extras inputs changed')
    write_json(args.output/'report.json',dict(status='complete',inputs=inputs,outputs=outputs,
      source_family='fxl_final_final',source_keys=len(selected),jobs=args.jobs,effective_nice=host_support.effective_nice(),
      elapsed_seconds=time.monotonic()-started,gpu_execution=False))
    print('EXTRAS_RESULT PASS',dict(collections.Counter(t[0] for t in tasks)),'swizzles',len(swizzles));return 0


def main():
    os.umask(0o077)
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--repo',type=Path,required=True)
    for n in ('inventory','translations','output'):p.add_argument('--'+n,type=Path,required=True)
    for n in ('toolchain','host-tools','ndk'):p.add_argument('--'+n,type=Path)      # a file of paths, or named from the two folders
    p.add_argument('--check',action='store_true');p.add_argument('--jobs',type=int,default=4)
    args=p.parse_args()
    for n in ('repo','inventory','translations','output'):setattr(args,n,getattr(args,n).resolve())
    for n in ('toolchain','host_tools','ndk'):
        if getattr(args,n) is not None:setattr(args,n,getattr(args,n).resolve())
    for n in ('tools/own_disc','tools/iter','tools/rpf7_inventory'):sys.path.insert(0,str(args.repo/n))
    from disc_builder import check_private_path
    check_private_path(args.output,'shader extras output')
    return overlays(args)

if __name__=='__main__':
    try:raise SystemExit(main())
    except (ValueError,OSError):
        print('EXTRAS_REFUSED; private partial output preserved',file=sys.stderr);raise SystemExit(2)
